def profile(domain, name, fallback_country):
    d = domain.lower().removeprefix("www.").removeprefix("m.")
    for key, p in PROFILES.items():
        if d == key or d.endswith("." + key):
            return {"name": p[0], "country": p[1], "ownership": p[2], "leaning": p[3], "profiled": True}
    tld = d.rsplit(".", 1)[-1]
    return {"name": name or d, "country": TLD.get(tld, fallback_country), "ownership": "Not profiled yet",
            "leaning": None, "profiled": False}
